// Copies the schemas blocks use from EZPG's generated API types. Run: npm run sync:contracts
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = process.env.EZPG_CONTRACTS ?? new URL("../../EZPG/contracts/types/generated/api.d.ts", import.meta.url).pathname;
const ROOTS = [
  "OrderOut",
  "OrderSummary",
  "CartOut",
  "CustomerProduct",
  "CustomerProductSummary",
  "AddressOut",
  "ReviewOut",
  "ClaimOut",
  "CustomerProvider",
];

const text = readFileSync(SOURCE, "utf8");
const start = text.indexOf("    schemas: {\n");
const lines = text.slice(start).split("\n").slice(1);
const blocks = new Map<string, string>();
for (let i = 0; i < lines.length; i++) {
  const head = /^ {8}(\w+): (.*)$/.exec(lines[i]);
  if (!head) {
    if (/^ {4}\};?$/.test(lines[i])) break;
    continue;
  }
  const body = [lines[i]];
  if (head[2] === "{") while (!/^ {8}\};$/.test(lines[i])) body.push(lines[++i]);
  blocks.set(head[1], body.join("\n"));
}

const picked = new Set<string>();
const visit = (name: string) => {
  if (picked.has(name)) return;
  const block = blocks.get(name);
  if (!block) throw new Error(`schema ${name} not found in ${SOURCE}`);
  picked.add(name);
  for (const [, ref] of block.matchAll(/components\["schemas"\]\["(\w+)"\]/g)) visit(ref);
};
ROOTS.forEach(visit);

const body = [...picked]
  .sort()
  .map((name) =>
    blocks
      .get(name)!
      .replace(/^\s*\/\*\*.*\*\/\n/gm, "")
      .replace(/^\s*\/\*\*[\s\S]*?\*\/\n/gm, "")
      .replace(/components\["schemas"\]\["(\w+)"\]/g, 'Schemas["$1"]')
      .replace(/^ {12}/gm, "    ")
      .replace(/^ {8}/gm, "  "),
  )
  .join("\n");

writeFileSync(
  new URL("../src/types/contract.ts", import.meta.url),
  `// Generated by scripts/sync-contracts.ts from EZPG contracts. Do not edit.\nexport interface Schemas {\n${body}\n}\n`,
);
console.log(`${picked.size} schemas`);
